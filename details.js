function renderRoute() {
  const match = window.location.hash.match(/^#device\/([a-z0-9-]+)$/i);
  if (!match) {
    detailView.hidden = true;
    homeView.hidden = false;
    document.title = t("title");
    return;
  }
  const device = devices.find((item) => item.id === match[1]);
  if (!device) {
    window.location.hash = "#devices";
    return;
  }
  renderDetail(device);
}

function openDevice(id) {
  if (window.location.hash === `#device/${id}`) renderRoute();
  else window.location.hash = `device/${id}`;
}

