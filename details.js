function fillList(elementId, items) {
  const list = document.getElementById(elementId);
  list.replaceChildren();
  items.forEach((item) => {
    const li = document.createElement("li");
    li.textContent = item;
    list.append(li);
  });
}

function addAction(device) {
  const target = document.getElementById("detail-actions");
  target.replaceChildren();
  if (device.download) {
    const link = document.createElement("a");
    link.className = "action-button";
    link.href = device.download;
    link.target = "_blank";
    link.rel = "noopener noreferrer";
    const label = document.createElement("span");
    label.textContent = detailI18n("downloadTest") || "Download A11 test build";
    link.append(label);
    target.append(link);
  } else {
    const button = document.createElement("button");
    button.type = "button";
    button.className = "action-button is-disabled";
    button.disabled = true;
    button.textContent = detailI18n("downloadUnavailable") || t("notAvailable");
    target.append(button);
  }
}

